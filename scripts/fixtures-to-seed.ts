/**
 * Turn scanner fixture folders into supabase/seed.sql, so the app has demo scans
 * (is_demo = true, readable without login) as soon as the database is reset.
 *
 *   npx tsx scripts/fixtures-to-seed.ts [fixturesDir=fixtures] [out=supabase/seed.sql]
 *
 * Every folder that contains findings.json + summary.json becomes one demo campaign
 * with one completed scan. Folders are searched recursively (fixtures/smoke/<name>, fixtures/<campaign>).
 * IDs are derived from the folder name, so re-running gives the same rows.
 */
import { createHash } from 'node:crypto';
import { access, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Finding } from '../src/types.ts';

const root = process.argv[2] ?? 'fixtures';
const out = process.argv[3] ?? 'supabase/seed.sql';

const exists = (p: string) => access(p).then(() => true, () => false);
const readJson = async <T>(p: string): Promise<T> => JSON.parse(await readFile(p, 'utf8')) as T;

/** Deterministic UUID (v4 layout) from a string. */
function uuidFrom(s: string): string {
  const h = createHash('sha256').update(s).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-${((parseInt(h[16], 16) & 3) | 8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const qj = (v: unknown): string => `${q(JSON.stringify(v ?? null))}::jsonb`;

interface Summary {
  url: string;
  scannedAt: string;
  totalMs: number;
  modules: Record<string, { ok: boolean; error?: string; durationMs: number; findings: number }>;
}

const STEP_LABELS: Record<string, string> = {
  capturePage: 'Capturing landing page…',
  checkLinks: 'Checking links and CTAs…',
  checkPerformance: 'Measuring mobile speed…',
  checkAccessibility: 'Checking accessibility…',
  extractOffer: 'Extracting price and conditions…',
  lighthouse: 'Running Lighthouse…',
};
const WEIGHT = { critical: 15, high: 7, medium: 3, low: 1 } as const; // same as public.compute_scan_score

async function findFixtureDirs(dir: string): Promise<string[]> {
  const found: string[] = [];
  if (await exists(path.join(dir, 'findings.json')) && await exists(path.join(dir, 'summary.json'))) found.push(dir);
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (e.isDirectory()) found.push(...await findFixtureDirs(path.join(dir, e.name)));
  }
  return found;
}

const dirs = (await findFixtureDirs(root)).sort();
const sql: string[] = [
  '-- GENERATED by scripts/fixtures-to-seed.ts from the scanner fixtures. Do not edit by hand.',
  '-- Demo campaigns (is_demo = true) are readable by everyone, including logged-out visitors.',
  '',
];

for (const dir of dirs) {
  const key = path.relative(root, dir).split(path.sep).join('/');
  const name = path.basename(dir);
  const summary = await readJson<Summary>(path.join(dir, 'summary.json'));
  const findings = await readJson<Finding[]>(path.join(dir, 'findings.json'));
  const offerFile = path.join(dir, 'extractOffer.json');
  const offer = (await exists(offerFile)) ? (await readJson<{ data?: unknown }>(offerFile)).data ?? null : null;

  const campaignId = uuidFrom(`campaign:${key}`);
  const scanId = uuidFrom(`scan:${key}`);
  const score = Math.max(0, 100 - findings.reduce((s, f) => s + WEIGHT[f.severity], 0));
  const completedAt = summary.scannedAt;
  const startedAt = new Date(new Date(completedAt).getTime() - summary.totalMs).toISOString();
  const shots = Object.fromEntries(
    [['desktop', 'capture.desktop.png'], ['desktopFold', 'capture.desktop.fold.png'], ['mobile', 'capture.mobile.png'], ['mobileFold', 'capture.mobile.fold.png']]
      .map(([k, file]) => [k, `demo/${campaignId}/${file}`]),
  );

  sql.push(`-- ${key}: ${findings.length} findings, score ${score}`);
  sql.push(
    `insert into public.campaigns (id, owner_id, name, product_category, landing_url, is_demo) values ` +
    `(${q(campaignId)}, null, ${q(name)}, 'general', ${q(summary.url)}, true) on conflict (id) do nothing;`,
  );
  sql.push(
    `insert into public.scans (id, campaign_id, owner_id, status, score, landing_url, offer, screenshots, total_ms, started_at, completed_at) values ` +
    `(${q(scanId)}, ${q(campaignId)}, null, 'completed', ${score}, ${q(summary.url)}, ${qj(offer)}, ${qj(shots)}, ${summary.totalMs}, ${q(startedAt)}, ${q(completedAt)}) on conflict (id) do nothing;`,
  );
  Object.entries(summary.modules).forEach(([step, m], i) => {
    sql.push(
      `insert into public.scan_steps (scan_id, name, label, position, status, findings_count, duration_ms, error) values ` +
      `(${q(scanId)}, ${q(step)}, ${q(STEP_LABELS[step] ?? step)}, ${i}, ${q(m.ok ? 'completed' : 'failed')}, ${m.findings}, ${m.durationMs}, ${q(m.error)}) on conflict (scan_id, name) do nothing;`,
    );
  });
  for (const f of findings) {
    const source = f.id.startsWith('links-') ? 'checkLinks' : f.id.startsWith('a11y-') ? 'checkAccessibility' : f.id.startsWith('perf-') ? 'checkPerformance' : null;
    sql.push(
      `insert into public.findings (scan_id, finding_key, source, category, severity, title, claim, evidence, rule, risk, fix, confidence) values ` +
      `(${q(scanId)}, ${q(f.id)}, ${q(source)}, ${q(f.category)}, ${q(f.severity)}, ${q(f.title)}, ${q(f.claim)}, ${qj(f.evidence)}, ${q(f.rule)}, ${q(f.risk)}, ${q(f.fix)}, ${f.confidence}) on conflict (scan_id, finding_key) do nothing;`,
    );
  }
  sql.push('');
}

await writeFile(out, sql.join('\n'));
console.log(`${dirs.length} fixture folder(s) -> ${out}`);
