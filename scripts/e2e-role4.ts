// E2E: pick a Colleague 4 campaign in the form, run a real scan, capture the report.
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://localhost:3000';
const campaign = process.argv[3] ?? 'Velunara';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
p.on('pageerror', (e) => console.log('pageerror', e.message.slice(0, 200)));
await p.goto(base + '/scan/new', { waitUntil: 'networkidle' });
await p.getByRole('button', { name: new RegExp(campaign) }).click();
await p.waitForTimeout(1200);
console.log('documents listed:', await p.locator('form ul li').count());
await p.screenshot({ path: 'ui/.shots/role4-1-new.png', fullPage: true });
const t0 = Date.now();
await p.getByRole('button', { name: 'Run Red Team scan' }).click();
await p.waitForURL(/\/scan\/SCN-[A-Z0-9-]+$/, { timeout: 180000 });
await p.waitForLoadState('networkidle');
await p.waitForTimeout(1500);
console.log('report', p.url(), ((Date.now() - t0) / 1000).toFixed(1) + 's');
await p.screenshot({ path: 'ui/.shots/role4-2-report.png', fullPage: true });
await b.close();
