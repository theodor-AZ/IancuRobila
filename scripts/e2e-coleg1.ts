// E2E through Colleague 1's screens: his form → real scan → his report.
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://localhost:3000';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
p.on('pageerror', (e) => console.log('pageerror', e.message.slice(0, 200)));
await p.goto(base + '/coleg1', { waitUntil: 'networkidle' });
await p.screenshot({ path: 'ui/.shots/coleg1-1-history.png', fullPage: true });
await p.goto(base + '/coleg1/new', { waitUntil: 'networkidle' });
await p.getByRole('button', { name: /demo/i }).first().click();
await p.waitForTimeout(400);
await p.screenshot({ path: 'ui/.shots/coleg1-2-new.png', fullPage: true });
const t0 = Date.now();
await p.getByRole('button', { name: /scan|audit|launch|start/i }).last().click();
await p.waitForURL(/\/progress/, { timeout: 20000 });
await p.waitForURL(/\/coleg1\/scan\/SCN-/, { timeout: 180000 });
await p.waitForLoadState('networkidle');
await p.waitForTimeout(1500);
console.log('coleg1 report', p.url(), ((Date.now() - t0) / 1000).toFixed(1) + 's');
await p.screenshot({ path: 'ui/.shots/coleg1-3-report.png', fullPage: true });
await b.close();
