import "server-only";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import type { Database, Json } from "./db/database.types";
import { findingToRow, rowToFinding } from "./db/findings";
import { campaignScore } from "./score";
import type { Scan, ScanStatus } from "./types";

/**
 * Scan store on Patrick's Supabase schema (supabase/migrations/20261107120000_init.sql).
 * Server-side only, with the service_role key (the pipeline writes steps, findings and score).
 * Uploaded files and captures stay on local disk for now (data/scans/<id>); moving them to the
 * ad-images / product-documents / screenshots buckets is the next step.
 *
 * Tested only at type level against the generated Database types, not yet on a live project.
 */
type DB = SupabaseClient<Database>;

let client: DB | null = null;
export function supabaseConfigured() {
  return !!(process.env.NEXT_PUBLIC_SUPABASE_URL && process.env.SUPABASE_SERVICE_ROLE_KEY);
}
function db(): DB {
  client ??= createClient<Database>(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!, {
    auth: { persistSession: false },
  });
  return client;
}

/** Pipeline steps in order; positions match SCAN_STEPS in the progress screen. */
const STEPS = [
  { name: "claims", label: "Extracting claims" },
  { name: "page", label: "Checking landing page" },
  { name: "links", label: "Testing links and speed" },
  { name: "a11y", label: "Running accessibility checks" },
  { name: "cross", label: "Cross-checking ad, page and evidence" },
];

interface Screens {
  desktop?: string;
  desktopSize?: { w: number; h: number };
  adImage?: string;
  documents?: string[];
  warnings?: string[];
  blocked?: boolean;
}

const toDbStatus = (s: ScanStatus) => (s === "done" ? "completed" : s === "running" ? "running" : "failed");

export async function sbSaveScan(scan: Scan): Promise<Scan> {
  // scan.id is a uuid generated by newScanId(), so local file folders can be created before the insert.
  const { data: campaign, error: e1 } = await db()
    .from("campaigns")
    .insert({ name: scan.campaign, brand: scan.brand, product_category: scan.productCategory, ad_text: scan.adText, landing_url: scan.landingUrl, ad_image_path: scan.adImage || null })
    .select("id")
    .single();
  if (e1 || !campaign) throw new Error(`Supabase: ${e1?.message}`);
  const screens: Screens = { adImage: scan.adImage, documents: scan.documents };
  const { data: row, error: e2 } = await db()
    .from("scans")
    .insert({ id: scan.id, campaign_id: campaign.id, status: "running", landing_url: scan.landingUrl, ad_text: scan.adText, screenshots: screens as unknown as Json, started_at: new Date().toISOString() })
    .select("id")
    .single();
  if (e2 || !row) throw new Error(`Supabase: ${e2?.message}`);
  await db().from("scan_steps").upsert(
    STEPS.map((s, i) => ({ scan_id: row.id, name: s.name, label: s.label, position: i, status: "pending" as const })),
    { onConflict: "scan_id,name" },
  );
  return { ...scan, id: row.id };
}

export async function sbUpdateScan(id: string, patch: Partial<Scan>): Promise<void> {
  const cur = await sbLoadScan(id);
  if (!cur) return;
  const next = { ...cur, ...patch };

  if (patch.step !== undefined) {
    const now = new Date().toISOString();
    await db().from("scan_steps").upsert(
      STEPS.map((s, i) => ({
        scan_id: id,
        name: s.name,
        label: s.label,
        position: i,
        status: i < patch.step! ? ("completed" as const) : i === patch.step ? ("running" as const) : ("pending" as const),
        ...(i === patch.step ? { started_at: now } : {}),
        ...(i < patch.step! ? { finished_at: now } : {}),
      })),
      { onConflict: "scan_id,name" },
    );
  }

  if (patch.brand !== undefined || patch.campaign !== undefined) {
    const { data } = await db().from("scans").select("campaign_id").eq("id", id).single();
    if (data) await db().from("campaigns").update({ brand: next.brand, name: next.campaign }).eq("id", data.campaign_id);
  }

  if (patch.findings) {
    await db().from("findings").delete().eq("scan_id", id);
    if (patch.findings.length) {
      const { error } = await db().from("findings").insert(patch.findings.map((f) => findingToRow(f, id, f.id.split("-")[0])));
      if (error) throw new Error(`Supabase: ${error.message}`);
    }
  }

  const screens: Screens = {
    desktop: next.pageCapture || undefined,
    desktopSize: next.pageCaptureSize,
    adImage: next.adImage,
    documents: next.documents,
    warnings: next.warnings,
    blocked: next.status === "blocked",
  };
  const finished = next.status !== "running";
  await db()
    .from("scans")
    .update({
      status: toDbStatus(next.status),
      error: next.error ?? null,
      total_ms: next.durationMs || null,
      screenshots: screens as unknown as Json,
      ...(finished ? { completed_at: new Date().toISOString(), score: campaignScore(next.findings) } : {}),
    })
    .eq("id", id);
}

export async function sbLoadScan(id: string): Promise<Scan | null> {
  if (!/^[0-9a-f-]{36}$/i.test(id)) return null;
  const { data: s } = await db().from("scans").select("*, campaigns(*), findings(*), scan_steps(*)").eq("id", id).maybeSingle();
  if (!s) return null;
  return rowToScan(s as unknown as ScanRow);
}

export async function sbListScans(): Promise<Scan[]> {
  const { data } = await db().from("scans").select("*, campaigns(*), findings(*), scan_steps(*)").order("created_at", { ascending: false }).limit(50);
  return ((data ?? []) as unknown as ScanRow[]).map(rowToScan);
}

type ScanRow = Database["public"]["Tables"]["scans"]["Row"] & {
  campaigns: Database["public"]["Tables"]["campaigns"]["Row"];
  findings: Database["public"]["Tables"]["findings"]["Row"][];
  scan_steps: Database["public"]["Tables"]["scan_steps"]["Row"][];
};

function rowToScan(s: ScanRow): Scan {
  const sc = (s.screenshots ?? {}) as unknown as Screens;
  const running = s.scan_steps.find((x) => x.status === "running");
  const done = s.scan_steps.filter((x) => x.status === "completed").length;
  const status: ScanStatus = s.status === "completed" ? "done" : s.status === "failed" ? (sc.blocked ? "blocked" : "failed") : "running";
  return {
    id: s.id,
    campaign: s.campaigns.name,
    brand: s.campaigns.brand ?? "",
    productCategory: s.campaigns.product_category,
    landingUrl: s.landing_url ?? s.campaigns.landing_url ?? "",
    adText: s.ad_text ?? s.campaigns.ad_text,
    adImage: sc.adImage ?? "",
    pageCapture: sc.desktop ?? "",
    pageCaptureSize: sc.desktopSize,
    documents: sc.documents ?? [],
    createdAt: s.created_at,
    durationMs: s.total_ms ?? 0,
    status,
    step: status === "done" ? STEPS.length : running ? running.position : done,
    error: s.error ?? undefined,
    warnings: sc.warnings,
    findings: s.findings.map(rowToFinding),
  };
}
